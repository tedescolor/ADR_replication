from adr.dist import Normal, Mixture, exp, sigmoid


def model(x):
    """Two-branch Gaussian mixture; polynomial parameters in t = 2*x0 - 1."""
    t = 2.0 * x[0] - 1.0
    m1 = -0.07681514261145533 + t * (1.536382166131036 + t * (-1.402711200092925 + t * (-2.8410584088456567 + t * (1.9455367047510128 + t * (0.8249862325576379 + t * (-0.9584909997676493))))))
    m2 = 0.23328195011859432 + t * (1.2246116082004312 + t * (3.3570998828610112 + t * (-2.328870639816883)))
    s1 = exp(-1.4636591184981764 + t * (-0.6704116328584551 + t * (-0.16555344580351694)))
    s2 = exp(-1.5102608004427964 + t * (-0.8323422597079402))
    w2 = sigmoid(-1.6623678385888967 + t * (7.4903388885405295 + t * (-8.729776742749062 + t * (2.369950666332554))))
    return Mixture([1.0 - w2, w2], [Normal(m1, s1), Normal(m2, s2)])
