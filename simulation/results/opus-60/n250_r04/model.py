    m1 = ((((0.8560157247875839) * t + -11.832364767172834) * t + 21.68524948343206) * t + -8.326588987655558) * t + 0.15616438771540597
    s1 = exp((-1.4085921928961658) * t + -0.8054955627381202)
    m2 = ((-11.316528782227092) * t + 15.3203504699533) * t + -5.010010437400055
