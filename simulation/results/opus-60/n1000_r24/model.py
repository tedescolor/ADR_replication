from adr.dist import Normal, StudentT, Mixture, exp, sigmoid


def model(x):
    t = x[0] - 0.5
    m1 = -0.105438517 + t * (2.86823068 + t * (-5.27747222 + t * (-19.8595752 + t * (28.8043159 + t * (17.4312451 + t * (-57.7489935))))))
    s1 = exp(-1.36690333 + t * (-1.45821342 + t * (-1.60639798)))
    m2 = -0.00122840337 + t * (6.25141747 + t * (-2.28574729))
    s2 = exp(-1.63938701 + t * (-1.22652641))
    w2 = sigmoid(-0.280029833) * sigmoid(2000.0 * (x[0] - 0.439866622))
    return Mixture([1.0 - w2, w2], [Normal(m1, s1), StudentT(7.728389447610494, m2, s2)])
