from adr.dist import Normal, Mixture, exp, sigmoid


def model(x):
    t = x[0]
    w = sigmoid((7.59941) + (-19.3237)*t**1 + (12.1713)*t**2)
    a = Normal((0.0124684) + (-7.70203)*t**1 + (20.5839)*t**2 + (-10.4214)*t**3, exp((-0.885719) + (-0.882949)*t**1 + (-0.689399)*t**2))
    b = Normal((-0.625295) + (-1.60541)*t**1 + (9.89582)*t**2 + (-8.66494)*t**3, exp((-0.221938) + (-2.14326)*t**1))
    return Mixture([w, 1 - w], [a, b])
