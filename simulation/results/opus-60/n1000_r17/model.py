    upper = (((-1.4942428536091936) * t + 1.7549073259958838) * t + 2.136954982614094) * t + 0.08947449512571486
    w = sigmoid(27028.014245859857 * (x[0] - 0.333962691359092)) * sigmoid(-0.07648134030560616)
