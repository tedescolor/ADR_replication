from adr.dist import Normal, Mixture, exp, sigmoid


def model(x):
    t = x[0]
    m1 = (((-15.22671398658384) * t + 20.93897002440984) * t + -6.660721166389658) * t + -0.19482739599876192
    s1 = exp((-1.415742072529676) * t + -0.9112998498068358)
    m2 = (5.1051527708947635) * t + -2.4920374948867563
    s2 = exp((-2.0718986471390703) * t + -0.1830961193813471)
    p = sigmoid(29.999998978260233 * (t - 0.37348837462057627)) * 0.6185649813673687
    return Mixture([1.0 - p, p], [Normal(m1, s1), Normal(m2, s2)])
