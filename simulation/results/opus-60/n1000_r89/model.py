from adr.dist import Normal, Mixture, exp


def model(x):
    """Two crossing branches (equal weight) with a shared heteroscedastic Gaussian noise."""
    z = 2.0 * x[0] - 1.0
    mA = (((((0.9392447635863608) * z + -0.17297876510049304) * z + -2.6051136252660574) * z + 1.5927893933556534) * z + 2.8626588927266785) * z + -0.0749960599413498
    mB = (((((-0.9816108125688465) * z + 1.1233471227006642) * z + -0.5813078841031019) * z + -1.6568820990068498) * z + 1.0453817841826547) * z + 0.0330561990898981
    s = exp((((-0.5677106234839241) * z + -0.25451188034739725) * z + -0.2558970119497384) * z + -1.479104565943392)
    return Mixture([0.5, 0.5], [Normal(mA, s), Normal(mB, s)])
