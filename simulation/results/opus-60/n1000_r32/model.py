from adr.dist import Normal, Mixture, exp, maximum


def model(x):
    t = x[0]
    m1 = ((-9.564099734335633 * t + 19.16137354078669) * t + -7.062435014784232) * t + -0.043743248287058396
    r = maximum(t - 0.5026783745996787, 0.0)
    m2 = m1 - (6.5647526712187085 * r + 3.727874816884916) * r
    s = exp((-0.791179472033602 * t + -0.5390870419349153) * t + -0.9859728910569389)
    w = 0.4403685710103434
    return Mixture([w, 1.0 - w], [Normal(m1, s), Normal(m2, s)])
