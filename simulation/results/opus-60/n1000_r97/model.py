from adr.dist import Normal, Mixture, exp, maximum, sigmoid


def model(x):
    t = x[0]
    m = ((((((-63.67558276562599) * t + 189.73511203817958) * t + -201.88608683182628) * t + 73.34908720218537) * t + 9.202447329674072) * t + -7.873274878731587) * t + 0.06622233887691954
    v = maximum(t - 0.24433685858199874, 0.0)
    d = (8.234372664465123 * v + -1.5698655975111129) * v
    w = sigmoid(-0.15352977053668587)
    lo = Normal(m, exp((-0.9529256404800466) * t + -1.18707769977547))
    hi = Normal(m + d, exp((-1.686355755604064) * t + -0.5899345707278777))
    return Mixture([1 - w, w], [lo, hi])
