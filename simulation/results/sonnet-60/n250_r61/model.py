from adr.dist import Normal, Mixture, exp


def model(x):
    t = x[0]
    mu = -0.09296250550688523 + t * (-6.565671545661875 + t * (18.475308382185034 + t * -10.662470555516794))
    s = exp(-0.9174903917131958 + t * (-3.375478158551896 + t * 4.786514624447788))
    return Mixture(
        [0.3625, 0.6375],
        [Normal(mu - 1.417118733149977 * s, 0.5227 * s),
         Normal(mu + 0.8058 * s, 0.6425 * s)],
    )
