def model(x):
    t = x[0]
    m = 0.10148896848924548 + t * (-11.040680196994066 + t * (39.173619896862554 + t * (-42.683084690489075 + t * 15.476255635322689)))
    ls = -1.0184641936923666 + t * (2.774062834029336 + t * (-23.329732552896285 + t * (43.01240328130476 + t * -20.834762796409557)))
    return Normal(m, exp(ls))
