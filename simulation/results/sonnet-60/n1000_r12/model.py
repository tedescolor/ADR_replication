from adr.dist import Normal, Mixture, exp, sigmoid


def model(x):
    t = x[0]
    z = -9.366541737070406 + t * (23.09241866214299 + t * -14.103388679355138)
    ma = 0.058602960294064955 + t * (-9.61082910097202 + t * (34.12910191870679 + t * (-36.361258249013005 + t * 10.779237049429142)))
    mb = -4.478427333886351 + t * (10.51173529068595 + t * -3.5001909462943046)
    sa = exp(-0.8531554287409086 + -1.3183767996936686 * t)
    return Mixture([sigmoid(-z), sigmoid(z)], [Normal(ma, sa), Normal(mb, 0.14738133755050223)])
