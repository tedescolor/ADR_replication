from adr.dist import Normal, exp


def model(x):
    u = x[0]
    m = 0.16087561378889745 + u * (-10.426347387856566 + u * (33.50266003967223 + u * (-31.144604569608568 + u * 8.690166318875214)))
    s = exp(-0.6938825868137335 + u * (-3.5830562949991633 + u * 5.0877782919016745))
    return Normal(m, s)
