from adr.dist import StudentT, exp, minimum, maximum


def model(x):
    a = x[0] - 3.0
    b = x[1] - 0.6
    c = x[5] - 2.0
    g = x[2] - 1.3
    mu = (1.8241 + 0.2824 * x[0] + 1.8337 * x[1] - 0.7726 * x[2] + 0.9224 * x[3]
          - 0.0108 * x[4] + 0.1873 * x[5] + 0.1188 * a * a + 0.7049 * b * b
          + 0.0109 * c * c + 0.0369 * g * g
          + 0.1287 * x[0] * x[5] - 0.222 * x[3] * x[5] - 0.2035 * x[1] * x[5])
    ls = (-1.1559 + 0.3252 * x[0] + 0.3768 * x[1] - 0.3178 * x[2] + 0.0753 * x[3]
          + 0.139 * x[4] - 0.2209 * x[5] + 0.1959 * a * a + 0.1871 * b * b
          + 0.0561 * c * c + 0.0792 * g * g)
    s = minimum(maximum(exp(ls), 0.3), 6.0)
    return StudentT(4.458, mu, s)
