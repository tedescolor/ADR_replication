from adr.dist import StudentT, exp, log, sigmoid

def model(x):
    la = log(x[7])
    s0 = -17.9389 + 0.118595 * x[0] + 0.0437693 * x[1] + 0.0647236 * x[2] + -0.0356769 * x[3] + -0.188214 * x[4] + 0.00727002 * x[5] + 0.0107048 * x[6]
    s0 = s0 + -0.393651 * (x[0] / 100 - 2.8) ** 2 + 23.7525 * (x[3] / 100 - 1.8) ** 2
    s0 = s0 + -2.55635 * (x[4] / 10 - 0.6) ** 2 + -0.000275025 * x[0] * x[3] + -2.63059 * (x[2] / 100 - 0.5) ** 2
    s1 = -22.4484 + 0.0529468 * x[0] + 0.108438 * x[1] + 0.123845 * x[2] + 0.0316117 * x[3] + 0.239965 * x[4] + 0.0153228 * x[5] + 0.0144838 * x[6]
    a = -2.44474 + 1.2648 * la + 0.00196489 * x[1] + -0.00343009 * x[2] + -0.0165054 * x[3] + 0.0058449 * x[0]
    ls = 0.561355 + 0.193489 * la + 0.00349984 * x[0] + 0.00489713 * x[1] + 0.00435314 * x[2] + -0.00638416 * x[3] + -0.0172394 * x[4]
    return StudentT(4.52452, s0 + s1 * sigmoid(a), exp(ls))
