from adr.dist import Normal, log, exp, maximum, minimum, sigmoid, where, dot


def model(x):
    l8 = log(x[8])
    l11 = log(x[11] + 0.1)
    l12 = log(maximum(x[12], 0) + 1000)
    l13 = log(maximum(x[13], 0) + 1000)
    l14 = log(maximum(x[14], 0) + 1000)
    m3 = minimum(x[3], 240)
    m4 = minimum(x[4], 240)
    s3 = sigmoid(x[3] - 192)
    s4 = sigmoid(x[4] - 193.5)
    mu = (-26.94046
        + dot([-21.48975, 23.14807, 0.08409439, 3.331379, -1.099561, -1.527998],
              [x[0], x[1], x[2], x[5], x[6], x[19]])
        + dot([6.581553, 0.7567433, 0.177894, -0.5660066, -0.0507843, 0.905517],
              [x[9], l8, l11, l12, l13, l14])
        + dot([-0.00788412, -0.07354568, 1.83589, 7.61972, 0.02593779, 0.4878753],
              [m3, m4, s3, s4, x[6] * x[6], x[0] * x[0]])
        + dot([-0.4719255, -0.02908768, -0.03617493],
              [x[1] * x[1], x[19] * x[19], x[5] * x[5]]))
    ls = (6.442576
        + dot([-0.1153074, 0.2901393, 0.03728097, -0.1354855, 0.1003329, -0.1463989],
              [x[0], x[1], x[2], x[5], x[6], x[19]])
        + dot([0.40761, 0.03717369, 0.01466452, 0.0244423, -0.108155, 0.1141115],
              [x[9], l8, l11, l12, l13, l14])
        + dot([-0.02620314, -0.004820209, 0.9457901],
              [m3, m4, s3]))
    return Normal(mu, exp(minimum(maximum(ls, -1), 4)))
