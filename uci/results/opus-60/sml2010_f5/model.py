from adr.dist import SkewNormal, exp, minimum, maximum, dot


def model(x):
    """Skew-normal; location = sparse quadratic polynomial, log-sd linear (x3, x4 capped)."""
    u = maximum(x, x)
    u[3] = minimum(x[3], 312.919)
    u[4] = minimum(x[4], 325.331)
    a, b, c, d, f, g = u[0:6]
    h, j, k, q, r, v = u[6:12]
    w, y, z, A = u[12:16]
    E = u[19]
    m = (-130.203963099
         + dot([-0.188987970781, 0.074446000438, -1.04529187631, 0.325408796799, 0.60232389271, -2.6700921367], u[0:6])
         + dot([4.0528644693, 0.0889867112724, 0.055317205725, 60.6512090017, 0.00861068057442, 6.18911344748], u[6:12])
         + dot([-2.90927717855e-05, 7.51494394235e-05, 0.000282052525417, -0.0336447754561], u[12:16])
         - 0.0620230191472 * E
         + h * dot([-0.282489161863, -0.862387058418, -0.0475692233015, 0.82347962551, -0.784405160059, -0.0059980605967], [v, a, E, b, q, g])
         + v * dot([-2.47413486451, 0.0801267044803, 2.10063949812, 0.20503987499, -2.59352227824e-05, 0.0192056046351], [b, v, a, g, y, d])
         + c * dot([-0.272868877155, 0.01183126999, -0.00050543979008, -0.0178545148065, -0.0190656387548], [q, f, r, c, h])
         + E * dot([-0.0879878448759, 1.79120055748e-05, -0.0104001449154, 0.00161295668597, -1.22125696554e-05], [q, y, E, A, z])
         + b * dot([-0.407999421348, -0.706229095954, 0.0668564406142], [q, g, b])
         + f * dot([-0.00156640646704, -1.61247417891e-06], [f, y])
         + a * dot([0.841567136731, -0.01671400324], [g, d])
         - 0.000913166569158 * j * k
         + 1.25981422021e-08 * r * w)
    ls = (0.89308049133
          + dot([0.186492853314, -0.0581624969591, 0.0397966564683, -0.0867299159522, 0.0702884245565, -0.882804339143], [a, b, c, g, h, q])
          - 0.107432751616 * E)
    return SkewNormal(m, exp(ls), 1.85895)
