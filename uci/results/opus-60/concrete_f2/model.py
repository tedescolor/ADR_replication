from adr.dist import LogNormal, dot, exp, log


def model(x):
    # log-normal: log-median quadratic in transformed covariates, log-sd quadratic in log age
    u0 = log(x[0]) - 5.56
    u1 = log(x[1] + 5) - 3.29
    u2 = log(x[2] + 5) - 3.05
    u3 = log(x[3]) - 5.2
    u4 = log(x[4] + 1) - 1.45
    u5 = x[5] - 974.7
    u6 = x[6] - 772.52
    u7 = log(x[7]) - 3.14
    m = 3.25622
    m = m + u0 * (dot((-0.4086142, -0.281591, -0.09470887, -1.060388, 0.07874492, -0.001577076), (u0, u1, u2, u3, u4, u5)) + dot((-0.00299176, -0.1187605), (u6, u7)) + 1.093572)
    m = m + u1 * (dot((0.0521505, -0.0281775, 0.02165609, 0.04725171, -0.0003572502, -0.0002938945), (u1, u2, u3, u4, u5, u6)) + 0.02071368 * u7 + 0.1392415)
    m = m + u2 * (dot((0.046965, 0.01190323, 0.005356338, 0.0001143037, 9.960159e-05, 0.009737164), (u2, u3, u4, u5, u6, u7)) + 0.09367265)
    m = m + u3 * (dot((-5.788069, -0.6997106, -0.01299777, -0.01393753, 0.1309063), (u3, u4, u5, u6, u7)) + -0.8883664)
    m = m + u4 * (dot((-0.06274089, -0.0001587398, -0.0002409102, -0.03649396), (u4, u5, u6, u7)) + 0.01477713)
    m = m + u5 * (dot((-5.975237e-06, -1.314406e-05, 0.0003445061), (u5, u6, u7)) + 0.0003031213)
    m = m + u6 * (dot((-1.179507e-05, 0.0003420478), (u6, u7)) + 0.0004293231)
    m = m + u7 * (0.2971146 + u7 * (-0.04664998 + -0.005715325 * u7))
    s = exp(-1.884031 + u7 * (-0.1467078 + 0.04011827 * u7))
    return LogNormal(m, s)
