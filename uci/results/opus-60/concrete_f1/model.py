from adr.dist import LogNormal, exp, Mixture, log, minimum, maximum

def model(x):
    a, b1, c, w = x[0], x[1], x[2], x[3]
    s, g, f = x[4], x[5], x[6]
    t = log(x[7])
    u = t*t
    v = u*t
    bb = a + b1 + c
    wr = w/bb
    r = log(wr)
    mu = -4.667076496 + 1.271316666*log(a) - 1.179889614*wr + 0.5895367536*b1/bb*t + 0.04783367254*(c > 3) + 0.08738438438*(s > 1) - 0.1135674271*(b1 > 3) - 1.866852246*c/bb - 0.3312828203*b1/bb + t*(0.0754983175*r - 0.0002791789927*f - 2.137141443e-05*g - 0.001456846655*b1 + 0.7044245767) + v*(-1.361472147e-05*a - 5.533203879e-05*b1 + 0.0004141997946*s) + b1*(8.897383332e-05*s + 1.857552871e-06*g + 2.440174184e-05*w + 1.068388813e-05*c + 3.944850475e-06*f - 0.006564077385) + u*(-0.002209405567*s + 0.0003283584112*b1) + 9.363685994e-07*f*g + c*(2.043667068e-05*f + 1.279948299e-05*w + 1.750184769e-05*g - 0.02857229149) - 3.24666754e-06*g*w
    ls = -2.15533889 - 0.2147842126*t + 0.01306882468*u + 0.0009739225899*a - 0.0255091131*s + 0.002051542469*b1 + 0.002857716561*c
    ls = minimum(maximum(ls, -3.558), -1.038)
    return Mixture([0.58089, 0.41911], [LogNormal(mu, exp(ls)), LogNormal(mu, exp(ls + 0.728452))])
