"""Conditional density of y: varying-coefficient linear mean (coefficients polynomial in x0),
log-scale cubic in x0, skew-normal edge correction near the [0.95, 1] support."""
from adr.dist import SkewNormal, exp, sigmoid, minimum, maximum, dot


def model(x):
    t = (x[0] - 5.16) / 2.63
    t2 = t * t
    t3 = t2 * t
    t4 = t2 * t2
    T = [1.0, t, t2, t3, t4, t4 * t]
    p = (
        dot([1.249785690366566, 1.0705583529086242, -0.3659646318130113, -0.25299532185250145, 0.10267956926189273, -0.008185197763345675], T)
        + -0.022312364584216232 * t3 * t3
        + dot([0.0032315048676424605, 1.7550703001631739e-06, 3.624020880294223e-05, -0.00012850045595328102, 4.9889528765680976e-05, -0.00017991884568932705], x[[1, 2, 3, 4, 5, 7]]) + dot([-0.0025752715921175608, 0.06143076071842888, 0.028634951084724827, 1.884940508095629, 0.000278970457074108, 0.06306014741976089], x[[9, 10, 12, 13, 14, 15]])
        + t * (dot([-0.0025740822559982513, -1.7569286720797032e-06, -3.824814383605405e-05, -1.7219641820731326e-05, -8.231289025324594e-05, -0.00010833694643364895], x[[1, 2, 3, 4, 5, 6]]) + dot([-8.498273940171166e-05, 0.0003133168650457891, 0.0069954630415717456, 0.00014821370129727387, -0.8359347467115013, 0.0001159141528493459], x[[7, 9, 10, 12, 13, 14]]) + -0.028353869839813597 * x[15])
        + t2 * (dot([-3.425629097433137e-05, 1.1452943941118551e-05, 5.262661052559215e-05, 0.0001730580183698544, 0.00842142494581375, -0.00664224841301622], x[[3, 4, 6, 9, 10, 12]]) + dot([0.2097990058853293, -5.18933341565665e-05], x[[13, 14]]))
        + t3 * dot([-0.023780735719746603, 1.011213929677711e-06, 2.8570442807276604e-05, 8.81154698614577e-05, -0.01436319466676356, 0.12393643545267782], x[[0, 3, 4, 9, 10, 13]])
        + t4 * 2.1910810571565288e-05 * x[3]
    )
    s = exp(dot([-5.686960593228573, 0.03164585841720771, -0.12442994710749639, -0.1459433275602596], T[:4]))
    wl = sigmoid(-3.3313658639582107 - 3.55129276471362 * (p - 0.95) / s)
    wh = sigmoid(-3.3313658639582107 - 3.55129276471362 * (1.0 - p) / s)
    dw = wl - wh
    loc = p + s * 1.625209576818053 * dw
    sc = s * exp(-0.5523567578252353 * (wl + wh))
    al = minimum(maximum(112.75415911592978 * dw, -8.0), 8.0)
    return SkewNormal(loc, sc, al)
