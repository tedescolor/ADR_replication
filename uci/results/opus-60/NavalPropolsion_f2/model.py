"""Comb density: y lies on a 0.001 grid (0.950..1.000) plus small Gaussian noise.
Grid weights follow an envelope centred on a regression mean; g is the operating-point index."""
import math
from adr.dist import Normal, Mixture, exp, log, minimum, maximum, dot


def model(x):
    g = (math.floor(x[1] / 3 + 0.5) - 5) / 4
    u = log(x[[13, 4, 9, 12]])
    v = log(x[[10, 3, 7, 5]])
    mu = 19.696320619956932 + g * (-1.5416707104587086 + g * (-3.161995418924484 + g * (-0.20523828359432653 + g * (0.16511677862233579 + g * (0.19790449084297726 + g * (0.5339107325326301 + g * (-0.09066524558468311 + g * (-0.4725681265198009)))))))) + dot([2.387531302224722, -0.7961177057335684, -1.87013623781728, 0.30329395226756045], u) + dot([0.10120800115530611, -0.04530960210291615, 0.006005958128665403, -0.0013877165154928192], v) + g * (dot([-1.2714187737179028, 0.20300525874127343, 0.20956366855523414, 0.11633724210090998], u) + dot([-0.00779469623139691, -0.07625337256312496, -0.14459318572207172, -0.022334417097499965], v)) + g ** 2 * (dot([-1.6180643503504046, 0.14071707452007948, 0.10448237033007947, -0.09788635626479597], u) + dot([0.07534966899864069, 0.1734992698120315, -0.0058812253647723125, -0.01969854461580674], v))
    mu = minimum(maximum(mu, 0.9), 1.05)
    sig = minimum(maximum(exp(-5.632791573936615 + g * (-0.10772812543450208 + g * (-0.6014630545814954 + g * (-0.3397876196215477 + g * (0.35822742352782))))), 0.0003), 0.05)
    s = 0.00014662951203376243

    def leaf(k):
        return exp(-0.5 * ((k * 0.001 - mu) / sig) ** 2) + 1e-300, Normal(k * 0.001, s)

    def grp(*p):
        w, c = zip(*p)
        return sum(w), Mixture(w, c)

    def blk(f, h):
        return lambda k: grp(f(k), f(k + h), f(k + 2 * h), f(k + 3 * h), f(k + 4 * h))

    h = blk(blk(leaf, 1), 5)
    return grp(h(950), h(975), leaf(1000))[1]
