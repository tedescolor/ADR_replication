from adr.dist import Normal, Mixture, exp, log, maximum, dot


def model(x):
    u = log(maximum(x[5], 1.0))
    z0 = [x[19], x[2], x[3], x[4], x[22]]
    e0 = dot([0.2063, 0.1419, 0.2841, -0.42, 0.4562], z0)
    e1 = dot([0.2731, 0.4111, 0.4046, -0.01902, 0.8576], z0)
    e2 = dot([0.2857, 0.6636, 0.5521, 0.2691, 2.404], z0)
    e3 = dot([0.3293, 0.4706, 0.2276, 0.5153, 1.833], z0)
    e4 = dot([-0.3017, 0.4076, -0.00609, 0.07431, -0.9676], z0)
    q = [1.0, x[0], u]

    def w(t, c):
        return exp(t + dot(c, q))

    s = 0.02009
    pa = [q[0], w(e0, [0.5295, -0.008492, -1.102]), w(e0, [-2.573, 0.01219, 0.07726]), w(e0, [-1.847, 0.003846, -0.7837]), w(e1, [-4.409, 0.01812, 0.1456])]
    pb = [w(e1, [-4.144, 0.01359, 0.01356]), w(e2, [-4.504, 0.004337, 0.1001]), w(e2, [-4.369, 0.003455, 0.2175]), w(e2, [-4.566, 0.00598, 0.268]), w(e2, [-5.477, 0.01321, 0.3299])]
    pc = [w(e3, [-2.654, -0.001573, 0.143]), w(e4, [2.47, -0.007108, -1.34]), w(e3, [-8.002, 0.07938, -0.511])]
    a = Mixture(pa, [Normal(0.0005516, s), Normal(0.4953, s), Normal(1.0, s), Normal(1.164, s), Normal(1.999, s)])
    b = Mixture(pb, [Normal(2.999, s), Normal(3.999, s), Normal(4.998, s), Normal(6.0, s), Normal(7.002, s)])
    c = Mixture(pc, [Normal(3.099, 0.5397), Normal(2.258, 0.3602), Normal(4.491, 1.0)])
    return Mixture([sum(pa), sum(pb), sum(pc)], [a, b, c])
