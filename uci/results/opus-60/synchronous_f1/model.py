from adr.dist import Normal, tanh, where


def model(x):
    """Two regimes. x3 > 20: x3 is a precise linear proxy for y. x3 near 0 (missing):
    y is predicted from (x0, x2) by a 17-unit tanh network."""
    x0, x2, x3 = x[0], x[2], x[3]
    f = (4.73627 - 1.24178 * x0 + 11.6663 * x2
         + 0.182153 * tanh(8.04625 * x0 - 0.000341645 * x2 - 44.5933)
         + 0.146232 * tanh(9.31489 * x0 - 0.0729071 * x2 - 42.4179)
         - 1.64696 * tanh(0.0666628 * x0 - 29.3244 * x2 + 5.2875)
         + 0.650516 * tanh(1.79185 * x0 + 0.603553 * x2 - 11.207)
         + 7.02959 * tanh(0.0189136 * x0 - 8.42659 * x2 + 1.28005)
         - 0.785379 * tanh(0.0522583 * x0 - 51.8957 * x2 + 7.18803)
         - 0.440034 * tanh(0.0309591 * x0 - 30.2219 * x2 + 1.59825)
         - 0.0332639 * tanh(-1.32652 * x0 - 38.094 * x2 + 12.1591)
         - 0.261013 * tanh(0.178722 * x0 - 54.9903 * x2 + 15.1134)
         + 0.264384 * tanh(0.436189 * x0 + 10.1584 * x2 - 1.63704)
         + 1.47262 * tanh(-2.64865 * x0 + 0.645264 * x2 + 9.24219)
         + 2.45016 * tanh(1.10706 * x0 - 0.729475 * x2 - 3.54571)
         + 0.133166 * tanh(8.98033 * x0 + 0.368484 * x2 - 36.3283)
         + 0.66311 * tanh(4.59176 * x0 - 0.615795 * x2 - 16.2555)
         - 0.505167 * tanh(-0.000329172 * x0 - 49.341 * x2 + 12.0469)
         + 0.280279 * tanh(4.94755 * x0 - 0.0276007 * x2 - 24.9667)
         + 0.814793 * tanh(-0.091262 * x0 + 42.5618 * x2 - 3.88014))
    on = x3 > 20.0
    loc = where(on, 1.18036261 + 0.000999300569 * x3, f)
    sd = where(on, 0.00293, 0.033)
    return Normal(loc, sd)
