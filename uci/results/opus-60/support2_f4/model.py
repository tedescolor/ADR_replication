from adr.dist import Normal, Mixture, softmax, exp, log

def chain(w, m, d, s):
    if len(w) == 1:
        return Normal(m, s)
    return Mixture([w[0], sum(w[1:])], [Normal(m, s), chain(w[1:], m + d, d, s)])

def quad(l, q, be, n):
    return [exp(l)] + quad(l + q, q - be - be, be, n - 1) if n > 0 else []

