from adr.dist import Normal, Mixture, exp, abs, dot


def model(x):
    i = int(round(x[1] / 3)) - 1
    T = [0.2371255937, 0.6093540519, 0.9997779975, 1.424083409, 1.835754573] + [2.235717875, 2.645043842, 3.129392088, 3.688143122]
    z = T[i] + dot(x[[9, 12, 4, 10, 3, 2]], [-0.00322483473, 0.04422799372, -0.0001593609266, 0.1337899152, 8.671273591e-05, 4.269219551e-06]) + dot(x[[13, 7, 15, 14]], [3.043831597, -0.00017077235, 0.06186010162, 8.124867261e-05]) + i * (dot(x[[9, 12, 4, 10, 3, 2]], [9.187021325e-05, -0.00416955686, 1.32046417e-05, -0.01517162938, -1.391844967e-05, -6.81627068e-07]) + dot(x[[13, 7]], [-0.4242405108, 6.461105245e-06]))
    sg = exp(-5.494849192 + i * (-0.002802254304 + i * (-0.01034324716)))
    s = 0.0001465671123
    h = 0.001
    Q = abs([0, 1, 2, 3, 4])

    def M(a):
        c = a + h * Q
        w = exp(-0.5 * ((c - z) / sg) ** 2) + 1e-12
        return Mixture(w, [Normal(c[0], s), Normal(c[1], s), Normal(c[2], s), Normal(c[3], s), Normal(c[4], s)]), sum(w), a + 5 * h

    m1, w1, a = M(min(max(round(z * 1000) - 12, 950), 976) * h)
    m2, w2, a = M(a)
    m3, w3, a = M(a)
    m4, w4, a = M(a)
    m5, w5, a = M(a)
    comb = Mixture([w1, w2, w3, w4, w5], [m1, m2, m3, m4, m5])
    return Mixture([1.0, 0.002], [comb, Normal(z, 2 * sg)])
